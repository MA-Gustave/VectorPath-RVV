def paired_ratios(rows, extras):
    """Matched ratios, segregated by role; no mixing sampled case populations."""
    group = defaultdict(dict)
    for row in [*rows, *extras]:
        group[row['group']][row['variant']] = row
    out = defaultdict(lambda: defaultdict(list))
    for record in group.values():
        if not {'A2', 'official', 'packed_plain'} <= record.keys() or not any(v in record for v in TARGETS):
            continue
        base = record['A2']
        for tag, item in record.items():
            if tag == 'A2':
                continue
            try:
                for measure in ('dom_all_gbps', 'stage1_gbps', 'stage2_gbps'):
                    ratio = float(item[measure]) / float(base[measure])
                    if not math.isfinite(ratio) or ratio <= 0:
                        raise ValueError('invalid ratio')
                    out[(item['role'], tag)][measure].append(ratio)
                    if tag not in ('official', 'packed_plain'):
                        packed_ratio = float(item[measure]) / float(record['packed_plain'][measure])
                        if not math.isfinite(packed_ratio) or packed_ratio <= 0:
                            raise ValueError('invalid packed comparison')
                        out[(item['role'], tag)]['vs_packed_' + measure].append(packed_ratio)
            except (KeyError, ValueError, TypeError, ZeroDivisionError):
                continue
    return out


class Campaign(Campaign91):
    REPORT_FILENAME = 'EXPLORATION_93.md'
    REPORT_TITLE = '# Test 93 — Stage 1 and experimental overhead isolation (3h max)'
    SNAPSHOT_FILES = tuple('EXPLORATION_93.md' if n == 'EXPLORATION_91.md' else n for n in FILES) + ('controls93.csv',)

    def __init__(self, source, workdir, hours=3, jobs=2, core=0, max_mib=8):
        if not 0 < float(hours) <= 3:
            raise ValueError('Test93 budget must be <=3 hours')
        super().__init__(source, workdir, hours, jobs, core, max_mib)
        missing = [key for key in TARGETS if key not in self.byid]
        if missing:
            raise RuntimeError('The fixed Test93 compositions are missing: ' + ', '.join(missing))
        self.targets = [self.byid[key] for key in TARGETS]
        self.extra_rows = []
        (self.root/'controls93.csv').write_text(','.join(FIELDS)+'\n', encoding='utf8')
        self.status.update(campaign='Test93', strategy='fixed_3h_four_build_diagnostic',
                           phase_progress={}, tested_points=list(TARGETS))
        self.meta.update(experiment='stage1_overhead_isolation_93',
                         diagnostic_targets=list(TARGETS),
                         experimental_controls=['A2', 'official', 'packed_plain', 'compositions'],
                         interpretation='A2 vs packed_plain isolates packed compile flags; '
                         'packed_plain vs policy=0 probes incremental research dispatch overhead '
                         'but not all implementation overhead. These are distinct builds, not '
                         'an attribution of any single Stage1 instruction.',
                         sampling='Fixed prespecified configurations, shared training corpora; '
                         'fresh-seed holdout last 20% of post-build time; no adaptive selection',
                         limitations=['Warm same-document throughput (not cold-cache)',
                                      'Full DOM is primary metric; Stage1/Stage2 are independent diagnostics',
                                      'No claim of production equivalence or statistical significance',
                                      'Different compilation switches can affect codegen; overhead is not fully causal'])

    def check(self, building=False):
        try:
            super().check(building)
        except support.Deadline as exc:
            raise support.Deadline(str(exc).replace('Test91', 'Test93')) from exc

    def native(self, *args, **kwargs):
        try:
            return super().native(*args, **kwargs)
        except support.Deadline as exc:
            raise support.Deadline(str(exc).replace('Test91', 'Test93')) from exc

    def checkpoint(self, phase=None, force=False):
        old = self.last_snap
        super().checkpoint(phase, force)
        # The Test91 checkpoint invokes self.snapshot() before we can append
        # the fourth build.  Reissue the complete SHA256 snapshot atomically.
        if force or self.last_snap != old:
            support.write_csv(self.root/'controls93.csv', self.extra_rows, FIELDS)
            self._report93()
            self.snapshot()

    def _report93(self):
        metrics = paired_ratios(self.rows, self.extra_rows)
        per_phase = defaultdict(int)
        for row in self.schedule:
            per_phase[row['phase']] += 1
        report = [self.REPORT_TITLE, '',
            f'State: {self.status.get("state")}; reason: {self.status.get("stop_reason", "")}',
            f'Experimental/reference observations: {len(self.rows)}; packed_plain observations: {len(self.extra_rows)};',
            f'Fully matched four-way groups: {len(self.extra_rows)}; validated compositions: {len(self.validated)}.',
            '', 'Four-way comparisons: A2 dedicated (100%), official VLS256,',
            'packed_plain (packed build WITHOUT runtime explorer) and research composition.',
            'Same JSON bytes and iterations, shuffled order. Different builds and compile-time flags.',
            'Rates are throughput, so ratio 0.75 means -25% throughput relative to A2.',
            '', '## Paired geometric-mean throughput relative to dedicated A2', '',
            '| Dataset | Variant | Paired groups | DOM / A2 | DOM delta | Stage1 delta | Stage2 delta | DOM / packed_plain |',
            '|---|---|---:|---:|---:|---:|---:|---:|']
        for (role, tag), m in sorted(metrics.items()):
            if not m.get('dom_all_gbps'):
                continue
            dom, s1, s2 = (gm(m[x]) for x in ('dom_all_gbps', 'stage1_gbps', 'stage2_gbps'))
            vs_packed = (f'{gm(m["vs_packed_dom_all_gbps"]):.3f}x' if m.get('vs_packed_dom_all_gbps') else '—')
            report.append(f'| {role} | {tag} | {len(m["dom_all_gbps"])} | {dom:.3f}x | '
                          f'{(dom-1)*100:+.2f}% | {(s1-1)*100:+.2f}% | {(s2-1)*100:+.2f}% | {vs_packed} |')
        report += ['', '## Region-switch trace diagnostics', '',
                   '| Candidate | Trace groups | Active region groups | Switch groups | Total switches |',
                   '|---|---:|---:|---:|---:|']
        for target in self.targets:
            traces = [r for r in self.diagnostics if r['variant'] == target['id']]
            report.append(f'| {target["id"]} | {len(traces)} | '
                          f'{sum(int(r["regions"])>0 for r in traces)} | '
                          f'{sum(int(r["changes"])>0 for r in traces)} | '
                          f'{sum(int(r["changes"]) for r in traces)} |')
        report += ['', '## Phase counts', '']
        report += [f'- {phase}: {count} four-way scheduled groups' for phase, count in sorted(per_phase.items())]
        report += ['', '## Interpretation / guardrails', '',
            '- `packed_plain / A2`: effect of the added packed compile-time switches in a non-exploratory build.',
            '- `policy=0 / packed_plain`: approximate incremental cost of the experimental research code path;',
            '  this is NOT a pure instrumentation ablation and cannot isolate one instruction.',
            '- `static policy=1 / packed_plain`: performance of fixed plans vs an identically packed base build.',
            '- `policy=3` counters (`diagnostics.csv`): check regional activation and switches before claims.',
            '- Evaluate training and fresh-seed holdout separately; compare matched corpus groups only.',
            '- All timed candidates must pass untimed full-DOM agreement with fallback.',
            '- The reported ratios are hot-parser throughput; Stage1/Stage2 are not addends to DOM.',
            '- No production configuration is changed or automatically selected.', '']
        support.atomic_text(self.root/self.REPORT_FILENAME, '\n'.join(report) + '\n')

    def group(self, point, spec, phase, trial=0):
        if not self.ensure_valid(point):
            return
        self.group_no += 1
        group = f'G{self.group_no:06d}'
        path = self.root/'active_corpus.json'
        self.status.update(current_candidate=point['id'], current_corpus=spec['id'], experiment_phase=phase)
        self.checkpoint(phase)
        try:
            item = generate(spec, path, self.check)
            self.manifest[spec['id']] = item
            # Every candidate and packed_plain get a full untimed DOM check.
            trace = self.native('compositions', 'trace', [path], point)
            if 'DOM_AGREES' not in trace:
                raise RuntimeError('Candidate DOM mismatch')
            for line in trace.splitlines():
                if line.startswith('TRACE '):
                    nums = list(map(int, line.split()[1:]))
                    if len(nums) != 7 or nums[0] != 1 or sum(nums[3:]) != item['bytes']:
                        raise RuntimeError('Trace accounting mismatch')
                    self.diagnostics.append(dict(zip(
                        ('variant','corpus','parses','regions','changes','balanced_bytes',
                         'dense_bytes','text_bytes','escape_bytes'),
                        [point['id'], spec['id'], *nums])))
                    break
            else:
                raise RuntimeError('Missing research trace')
            if 'DOM_AGREES' not in self.native('packed_plain','check',[path],point):
                raise RuntimeError('Packed plain DOM mismatch')
            iters = max(1, min(128, 1048576 // item['bytes']))
            order = ['official', 'A2', 'packed_plain', point['id']]
            self.rng.shuffle(order)
            self.schedule.append(dict(group=group, phase=phase, role=spec['role'],
                                      candidate=point['id'], corpus=spec['id'],
                                      trial=trial, order=order))
            for tag in order:
                binary = 'compositions' if tag == point['id'] else tag
                text = self.native(binary, 'split', [path, iters], point)
                dom, s1, s2, seconds, _, _, actual, size = support.parse_split_output(text)
                if actual != iters or size != item['bytes']:
                    raise RuntimeError('Native benchmark echo mismatch')
                row = dict(timestamp=support.now(), group=group, phase=phase,
                           role=spec['role'], variant=tag, corpus=spec['id'],
                           family='+'.join(item['effective_families']),
                           layout=spec['layout'], bytes=size, iterations=iters, trial=trial,
                           dom_all_gbps=dom, stage1_gbps=s1, stage2_gbps=s2, seconds=seconds)
                if tag == 'packed_plain':
                    self.extra_rows.append(row)
                    file_name='controls93.csv'
                else:
                    self.rows.append(row)
                    file_name='map.csv'
                with (self.root/file_name).open('a', newline='', encoding='utf8') as f:
                    writer = csv.DictWriter(f, fieldnames=FIELDS)
                    if f.tell() == 0:
                        writer.writeheader()
                    writer.writerow(row)
                    f.flush(); os.fsync(f.fileno())
                self.checkpoint(phase)
        except (support.Stopped, support.Safety, support.Deadline):
            raise
        except Exception as exc:
            self.rejected[point['id']] = str(exc)
            self.failure('test93_candidate_or_measurement', point['id'], exc)
            if str(exc).startswith('Packed plain') or ('binary' in locals() and binary in ('official', 'A2', 'packed_plain')):
                raise
        finally:
            with contextlib.suppress(FileNotFoundError):
                path.unlink()

    def _anchors(self):
        # Stress major Test92 regressing families and region transitions, across
        # 64 KiB, 1 MiB and 8 MiB. The shared list never depends on Test93 scores.
        cases = [('ascii',65536), ('dense',65536), ('escaped',65536),
                 ('utf8',65536), ('long_strings',1048576), ('unicode_escape',65536),
                 ('nested',1048576), ('floats',65536), ('many_keys',1048576),
                 ('utf8',8388608), ('long_strings',8388608)]
        anchors = [next(s for s in self.specs if s['kinds']==[kind] and
                        s['target']==size and s['layout']=='interleaved')
                   for kind, size in cases]
        region = next(s for s in self.specs if len(s['kinds'])>=3 and
                      {'utf8','long_strings'} & set(s['kinds']) and
                      s['target']==1048576 and s['layout']=='regions16384')
        anchors.append(region)
        return anchors

    def explore(self):
        if not self.build(PACKED_PLAIN, None):
            raise RuntimeError('Non-experimental packed_plain reference build failed')
        self.meta['coverage'] = dict(passed=list(self.binaries), expected=4)
        start=time.monotonic()
        training_end=start+max(0,self.deadline_mono-start)*.80
        anchors=self._anchors()
        # Give diagnostics a minimum initial equal-JSON coverage; all prechosen
        # variants participate on each shared corpus before repeats.
        trial=0
        while time.monotonic()<training_end:
            for spec in anchors:
                order=self.targets.copy()
                self.rng.shuffle(order)
                for point in order:
                    if time.monotonic()>=training_end:
                        break
                    if point['id'] not in self.rejected:
                        self.group(point,spec,'diagnostic' if trial==0 else 'repeat',trial)
                if time.monotonic()>=training_end:
                    break
            trial+=1
        self.status['phase_progress']['training_rounds']=trial
        # Frozen BEFORE holdout. Fresh seeds are never fed into training or
        # winner selection; all surviving plans get the same JSON every round.
        self.frozen=[p['id'] for p in self.targets if p['id'] not in self.rejected]
        self.checkpoint('holdout',force=True)
        if not self.frozen:
            raise RuntimeError('No validated candidates for fresh-seed holdout')
        for trial in range(10000):
            if time.monotonic()>=self.deadline_mono:
                break
            base=anchors[trial%len(anchors)]
            spec=dict(base,id=f'H{trial:05d}',seed=SEED+9300000000+trial*99991,
                      role='holdout')
            order=self.frozen.copy()
            self.rng.shuffle(order)
            for key in order:
                if time.monotonic()>=self.deadline_mono:
                    break
                self.group(self.byid[key],spec,'holdout',trial)

    def execute(self):
        # Reuse the proven native v5 build, disk-safety, exclusive-lock,
        # validation and remote checkpoint lifecycle from Test91.
        # We override the build set by temporarily providing a narrow hook:
        # build the extra no-exploration packed control immediately before
        # exploration via our explore override (after base three builds).
        super().execute()
        if self.status.get('stop_reason','').startswith('Test91'):
            self.status['stop_reason']=self.status['stop_reason'].replace('Test91','Test93')
            self.checkpoint(force=True)
